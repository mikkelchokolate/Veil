package cli

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// TestPostinstallWarnsAboutForeignUnitDropIns runs the shipped helper: a drop-in
// the operator (or a previous root compromise) left in a Veil unit's .d
// directory rides the upgrade's try-restart, so install must point at it instead
// of silently trusting the unit (#1278 item 2). Veil's own generated drop-in and
// anything carrying the generated marker stay quiet.
func TestPostinstallWarnsAboutForeignUnitDropIns(t *testing.T) {
	body, err := os.ReadFile("../../packaging/scripts/postinstall.sh")
	if err != nil {
		t.Fatal(err)
	}
	code := strings.ReplaceAll(string(body), "\r\n", "\n")
	start := strings.Index(code, "warn_foreign_dropins() {")
	if start < 0 {
		t.Fatal("postinstall has no warn_foreign_dropins helper")
	}
	end := strings.Index(code[start:], "\n    # end: warn_foreign_dropins")
	if end < 0 {
		t.Fatal("could not find the end of warn_foreign_dropins")
	}
	helper := code[start : start+end]

	root := t.TempDir()
	dirs := map[string][]string{
		"veil.service.d":       {"10-veil-install.conf", "override.conf", "20-copied.conf"},
		"veil-caddy.service.d": {"20-operator.conf"},
		"other-app.service.d":  {"foreign.conf"},
	}
	for dir, names := range dirs {
		if err := os.MkdirAll(filepath.Join(root, dir), 0o755); err != nil {
			t.Fatal(err)
		}
		for _, name := range names {
			header := ""
			if name == "10-veil-install.conf" || name == "20-copied.conf" {
				header = "# Generated by veil install.\n"
			}
			if err := os.WriteFile(filepath.Join(root, dir, name), []byte(header+"[Service]\n"), 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	script := helper + "\nwarn_foreign_dropins \"$1\"\n"
	command := exec.Command("sh", "-c", script, "sh", root)
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("helper failed: %v\n%s", err, output)
	}
	text := string(output)
	for _, want := range []string{"override.conf", "20-operator.conf", "WARNING"} {
		if !strings.Contains(text, want) {
			t.Fatalf("warning does not mention %q:\n%s", want, text)
		}
	}
	for _, unwanted := range []string{"10-veil-install.conf", "20-copied.conf", "other-app.service.d"} {
		if strings.Contains(text, unwanted) {
			t.Fatalf("warning must not mention %q:\n%s", unwanted, text)
		}
	}
}
